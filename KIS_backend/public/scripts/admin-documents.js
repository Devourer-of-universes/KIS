function handleStepDragStart(event, idx) {
    draggedStepIndex = idx;
    event.target.classList.add('dragging');
    event.dataTransfer.effectAllowed = 'move';
    event.dataTransfer.setData('text/plain', String(idx));
}

function handleStepDragEnd(event) {
    event.target.classList.remove('dragging');
    document.querySelectorAll('.wf-step-card').forEach(card => {
        card.classList.remove('drag-over');
    });
    draggedStepIndex = null;
}

function handleStepDragOver(event, idx) {
    event.preventDefault();
    event.dataTransfer.dropEffect = 'move';
    
    if (draggedStepIndex === null || draggedStepIndex === idx) return;
    
    const targetCard = event.currentTarget;
    targetCard.classList.add('drag-over');
}

function handleStepDragLeave(event) {
    event.currentTarget.classList.remove('drag-over');
}

function handleStepDrop(event, targetIdx) {
    event.preventDefault();
    
    if (draggedStepIndex === null || draggedStepIndex === targetIdx) {
        return;
    }
    
    // Перемещаем элемент в массиве
    const [movedStep] = currentWorkflowSteps.splice(draggedStepIndex, 1);
    currentWorkflowSteps.splice(targetIdx, 0, movedStep);
    
    // Если редактировался перемещаемый этап — обновляем выделение
    if (selectedStepIndex === draggedStepIndex) {
        selectedStepIndex = targetIdx;
    } else if (selectedStepIndex !== null) {
        // Корректируем выделение, если оно сдвинулось
        if (selectedStepIndex === draggedStepIndex) {
            selectedStepIndex = targetIdx;
        } else if (draggedStepIndex < selectedStepIndex && targetIdx >= selectedStepIndex) {
            selectedStepIndex--;
        } else if (draggedStepIndex > selectedStepIndex && targetIdx <= selectedStepIndex) {
            selectedStepIndex++;
        }
    }
    
    draggedStepIndex = null;
    renderWorkflowSteps();
}

