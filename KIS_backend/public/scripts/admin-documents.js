async function loadCounterparties() {
    const tbody = document.getElementById('counterpartiesTableBody');
    if (!tbody) return;

    tbody.innerHTML = '<tr><td colspan="7" class="loading-row">Загрузка...</td></tr>';

    try {
        const search = document.getElementById('counterpartiesSearch')?.value || '';
        const activeOnly = document.getElementById('counterpartiesActiveOnly')?.checked ? 'true' : 'false';
        const offset = (counterpartiesPage - 1) * counterpartiesPerPage;

        const params = new URLSearchParams({
            search,
            active_only: activeOnly,
            limit: counterpartiesPerPage,
            offset
        });

        const data = await apiRequest(`/api/counterparties?${params.toString()}`);
        counterpartiesList = data.counterparties || [];
        renderCounterparties(data.total || 0);
    } catch (error) {
        console.error('Load counterparties error:', error);
        tbody.innerHTML = `<tr><td colspan="7" class="loading-row" style="color: var(--c_error);">${escapeHtml(error.message)}</td></tr>`;
    }
}

function renderCounterparties(total) {
    const tbody = document.getElementById('counterpartiesTableBody');
    if (!tbody) return;

    if (counterpartiesList.length === 0) {
        tbody.innerHTML = '<tr><td colspan="7" class="loading-row">📭 Нет контрагентов</td></tr>';
    } else {
        tbody.innerHTML = counterpartiesList.map(cp => {
            const statusBadge = cp.is_active
                ? '<span class="status-badge status-active">🟢</span>'
                : '<span class="status-badge status-inactive">⚫</span>';

            return `
                <tr>
                    <td><strong>${escapeHtml(cp.name)}</strong>${cp.full_name ? `<br><small style="color: var(--c_surf_txt);">${escapeHtml(cp.full_name)}</small>` : ''}</td>
                    <td><code>${escapeHtml(cp.inn || '—')}</code></td>
                    <td>${escapeHtml(cp.contact_person || '—')}${cp.contact_position ? `<br><small>${escapeHtml(cp.contact_position)}</small>` : ''}</td>
                    <td>${escapeHtml(cp.phone || '—')}</td>
                    <td>${escapeHtml(cp.email || '—')}</td>
                    <td>${statusBadge}</td>
                    <td>
                        <button class="btn-icon buttonbase" title="Редактировать" onclick="openCounterpartyModal(${cp.id})">✏️</button>
                        <button class="btn-icon buttonbase" title="Удалить" onclick="deleteCounterparty(${cp.id})" style="color: #dc3545;">🗑️</button>
                    </td>
                </tr>
            `;
        }).join('');
    }

    // Пагинация
    const totalPages = Math.ceil(total / counterpartiesPerPage);
    const container = document.getElementById('cpPaginationButtons');
    const fromEl = document.getElementById('cpShowingFrom');
    const toEl = document.getElementById('cpShowingTo');
    const totalEl = document.getElementById('cpTotalCount');

    if (fromEl) fromEl.textContent = total === 0 ? 0 : (counterpartiesPage - 1) * counterpartiesPerPage + 1;
    if (toEl) toEl.textContent = Math.min(counterpartiesPage * counterpartiesPerPage, total);
    if (totalEl) totalEl.textContent = total;

    if (!container) return;

    if (totalPages <= 1) {
        container.innerHTML = '';
        return;
    }

    let html = '';
    if (counterpartiesPage > 1) {
        html += `<button class="pagination-btn" onclick="counterpartiesPage = ${counterpartiesPage - 1}; loadCounterparties()">←</button>`;
    }
    for (let i = Math.max(1, counterpartiesPage - 2); i <= Math.min(totalPages, counterpartiesPage + 2); i++) {
        html += `<button class="pagination-btn ${i === counterpartiesPage ? 'active' : ''}" onclick="counterpartiesPage = ${i}; loadCounterparties()">${i}</button>`;
    }
    if (counterpartiesPage < totalPages) {
        html += `<button class="pagination-btn" onclick="counterpartiesPage = ${counterpartiesPage + 1}; loadCounterparties()">→</button>`;
    }
    container.innerHTML = html;
}

