async function handleTemplateFileSelect(e) {
    const file = e.target.files[0];
    if (!file) return;
    
    if (!file.name.toLowerCase().endsWith('.docx')) {
        showToast('Только .docx файлы', 'error');
        e.target.value = '';
        return;
    }
    
    // Показываем индикатор загрузки
    const detectedDiv = document.getElementById('detectedPlaceholders');
    const detectedList = document.getElementById('detectedPlaceholdersList');
    if (detectedDiv) detectedDiv.style.display = 'block';
    if (detectedList) detectedList.innerHTML = '<span style="color: var(--c_surf_txt);">⏳ Парсинг .docx...</span>';
    
    try {
        const formData = new FormData();
        formData.append('template_file', file);
        
        const result = await apiRequest('/api/document-templates/parse-docx', {
            method: 'POST',
            body: formData
        });
        
        currentTemplateDetectedPlaceholders = result.placeholders || [];
        
        // Показываем обнаруженные плейсхолдеры
        renderDetectedPlaceholders();
        
        // Обновляем маппинг — сразу, без сохранения
        renderPlaceholdersMapping();
        
        if (currentTemplateDetectedPlaceholders.length === 0) {
            showToast('В .docx не найдено плейсхолдеров вида {Имя}', 'warning');
        } else {
            showToast(`Найдено ${currentTemplateDetectedPlaceholders.length} плейсхолдеров`, 'success');
        }
    } catch (error) {
        console.error('Parse docx error:', error);
        showToast('Ошибка парсинга: ' + error.message, 'error');
        if (detectedList) detectedList.innerHTML = '<span style="color: var(--c_error);">Ошибка парсинга</span>';
    }
}

function renderDetectedPlaceholders() {
    const container = document.getElementById('detectedPlaceholders');
    const list = document.getElementById('detectedPlaceholdersList');

    if (!container || !list) return;

    if (currentTemplateDetectedPlaceholders.length === 0) {
        container.style.display = 'none';
        return;
    }

    container.style.display = 'block';
    list.innerHTML = currentTemplateDetectedPlaceholders.map(p => 
        `<span class="placeholder-chip">{${escapeHtml(p)}}</span>`
    ).join('');
}

function renderPlaceholdersMapping() {
    const container = document.getElementById('placeholdersMapping');
    if (!container) return;

    const placeholders = currentTemplateDetectedPlaceholders;

    if (!placeholders || placeholders.length === 0) {
        container.innerHTML = `
            <div class="empty-fields">
                <small>Плейсхолдеры появятся после загрузки .docx</small>
            </div>
        `;
        return;
    }

    // Формируем список доступных полей для маппинга
    const fieldOptions = [
        { value: '', label: '— Не использовать —' },
        ...currentTemplateFields.map(f => ({ value: f.key, label: f.label + ' (' + f.key + ')' })),
        { value: '__manual__', label: '— Ввести вручную —' }
    ];

    container.innerHTML = placeholders.map(ph => {
        const mappedValue = currentTemplatePlaceholders[ph] || '';
        const optionsHtml = fieldOptions.map(opt => 
            `<option value="${escapeHtml(opt.value)}" ${mappedValue === opt.value ? 'selected' : ''}>${escapeHtml(opt.label)}</option>`
        ).join('');

        return `
            <div class="placeholder-mapping-row">
                <span class="placeholder-label">{${escapeHtml(ph)}}</span>
                <span class="mapping-arrow">→</span>
                <select class="form-select" data-placeholder="${escapeHtml(ph)}" onchange="onPlaceholderMappingChange(this)">
                    ${optionsHtml}
                </select>
            </div>
        `;
    }).join('');
}

function onPlaceholderMappingChange(select) {
    const placeholder = select.dataset.placeholder;
    const value = select.value;
    if (value) {
        currentTemplatePlaceholders[placeholder] = value;
    } else {
        delete currentTemplatePlaceholders[placeholder];
    }
}

async function saveDocumentTemplate() {
    const id = document.getElementById('documentTemplateId').value;
    const isEdit = !!id;

    const name = document.getElementById('documentTemplateName').value.trim();
    const documentTypeId = document.getElementById('documentTemplateType').value;

    if (!name) { showToast('Введите название', 'error'); return; }
    if (!documentTypeId) { showToast('Выберите тип документа', 'error'); return; }

    const templateData = {
        fields: currentTemplateFields,
        placeholders: currentTemplatePlaceholders
    };

    const formData = new FormData();
    formData.append('name', name);
    formData.append('document_type_id', documentTypeId);
    formData.append('description', document.getElementById('documentTemplateDescription').value.trim());
    formData.append('template_data', JSON.stringify(templateData));
    formData.append('default_workflow_template_id', document.getElementById('documentTemplateWorkflow').value || '');
    formData.append('access_mode', document.getElementById('documentTemplateAccessMode').value);

    const fileInput = document.getElementById('documentTemplateFile');
    if (fileInput.files[0]) {
        formData.append('template_file', fileInput.files[0]);
    }

    try {
        const url = isEdit ? `/api/document-templates/${id}` : '/api/document-templates';
        const method = isEdit ? 'PUT' : 'POST';

        await apiRequest(url, {
            method,
            body: formData
        });

        showToast(isEdit ? 'Шаблон обновлён' : 'Шаблон создан', 'success');
        closeDocModal('documentTemplateModal');
        loadDocumentTemplates();
    } catch (error) {
        console.error('Save document template error:', error);
        showToast(error.message, 'error');
    }
}

