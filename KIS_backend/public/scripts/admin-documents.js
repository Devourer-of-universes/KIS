function generateFieldKey(type, num) {
    const prefixMap = {
        text: 'text_field',
        textarea: 'textarea_field',
        number: 'number_field',
        date: 'date_field',
        select: 'select_field',
        checkbox: 'checkbox_field',
        user: 'user_id',
        counterparty: 'counterparty_id'
    };
    const prefix = prefixMap[type] || 'field';
    // Для user/counterparty не добавляем номер, если там уже есть _id
    if (prefix.endsWith('_id')) return prefix;
    return `${prefix}_${num}`;
}

