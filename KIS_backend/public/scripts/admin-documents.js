/**
 * Открыть редактор шаблона процесса (как секцию)
 */
async function openWorkflowTemplateEditor(templateId = null) {
    currentEditingWorkflowTemplateId = templateId;
    currentWorkflowSteps = [];
    selectedStepIndex = null;
    
    // Сбрасываем форму
    const nameInput = document.getElementById('workflowTemplateName');
    const descInput = document.getElementById('workflowTemplateDescription');
    const scopeInput = document.getElementById('workflowTemplateScope');
    const idBadge = document.getElementById('workflowTemplateEditorIdBadge');
    
    if (nameInput) nameInput.value = '';
    if (descInput) descInput.value = '';
    if (scopeInput) scopeInput.value = 'personal';
    if (idBadge) idBadge.textContent = '';
    
    if (templateId) {
        document.getElementById('workflowTemplateEditorTitle').textContent = '✏️ Редактирование шаблона';
        if (idBadge) idBadge.textContent = 'ID: ' + templateId;
        
        try {
            const data = await apiRequest(`/api/workflow-templates/${templateId}`);
            const tmpl = data.template;
            
            if (nameInput) nameInput.value = tmpl.name;
            if (descInput) descInput.value = tmpl.description || '';
            if (scopeInput) scopeInput.value = tmpl.scope || 'personal';
            
            currentWorkflowSteps = (tmpl.steps || []).map(s => ({
                id: s.id,
                type: s.type || 'approval',
                role_label: s.role_label || '',
                assignee_type: s.assignee_type || 'user',
                assignee_user_id: s.assignee_user_id || s.user_id || null,
                assignee_post_id: s.assignee_post_id || null,
                assignee_department_id: s.assignee_department_id || null,
                assignee_role_id: s.assignee_role_id || null,
                user: s.user || null
            }));
        } catch (error) {
            console.error('Load workflow template error:', error);
            showToast(error.message, 'error');
            return;
        }
    } else {
        document.getElementById('workflowTemplateEditorTitle').textContent = '🔄 Новый шаблон процесса';
    }
    
    // Открываем секцию
    openAdminSection('workflow-template-editor-section');
    setActiveNavButton(document.getElementById('nav-btn-documents'));
    
    // Рендерим этапы
    renderWorkflowSteps();
    updateWorkflowEditorStats();
}

