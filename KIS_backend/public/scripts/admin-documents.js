function renderStepAssigneeFieldsHtml(idx, step) {
    const assigneeType = step.assignee_type || 'user';
    const assigneeLabel = step.user?.full_name 
        || (step.assignee_user_id ? `ID: ${step.assignee_user_id}` : 'Не выбран');
    const isMissing = !isStepAssigneeValid(step);
    
    // 1. Конкретный пользователь
    if (assigneeType === 'user') {
        return `
            <div class="wf-step-editor-field">
                <label>Пользователь *</label>
                <button type="button" 
                        class="wf-user-picker-btn ${isMissing ? 'missing' : ''}"
                        onclick="openUserSelectorForStep(${idx})">
                    <span class="wf-user-picker-btn-text">${escapeHtml(assigneeLabel)}</span>
                    <span class="wf-user-picker-btn-hint">👤 Выбрать</span>
                </button>
                ${isMissing ? '<small style="color: var(--c_error); font-size: 11px;">⚠️ Выберите пользователя</small>' : ''}
            </div>
        `;
    }
    
    // 2. Автор
    if (assigneeType === 'author') {
        return `
            <div class="wf-step-editor-field">
                <div style="padding: 10px; background: var(--c_acchalf); border-radius: 8px; font-size: 12px; color: var(--c_bg_txt); line-height: 1.5;">
                    ℹ️ Выполнит <b>автор документа</b>.<br>
                    <small style="color: var(--c_surf_txt);">Определяется при запуске.</small>
                </div>
            </div>
        `;
    }
    
    // 3. Руководитель отдела
    if (assigneeType === 'department_manager') {
        return `
            <div class="wf-step-editor-field">
                <div style="padding: 10px; background: var(--c_acchalf); border-radius: 8px; font-size: 12px; color: var(--c_bg_txt); line-height: 1.5;">
                    ℹ️ Выполнит <b>руководитель отдела автора</b>.<br>
                    <small style="color: var(--c_surf_txt);">Определяется при запуске.</small>
                </div>
            </div>
        `;
    }
    
    // 4. Должность
    if (assigneeType === 'post') {
        const postOptions = stepEditorPosts.map(p => {
            const selected = step.assignee_post_id === p.id ? 'selected' : '';
            return `<option value="${p.id}" ${selected}>${escapeHtml(p.name)}${p.department_name ? ' (' + escapeHtml(p.department_name) + ')' : ''}</option>`;
        }).join('');
        
        const deptOptions = stepEditorDepartments.map(d => {
            const selected = step.assignee_department_id === d.id ? 'selected' : '';
            const prefix = '—'.repeat(d.level || 0) + ' ';
            return `<option value="${d.id}" ${selected}>${prefix}${escapeHtml(d.name)}</option>`;
        }).join('');
        
        return `
            <div class="wf-step-editor-field">
                <label>Должность *</label>
                <select onchange="updateStepProperty(${idx}, 'assignee_post_id', this.value ? parseInt(this.value) : null)">
                    <option value="">— Выберите —</option>
                    ${postOptions}
                </select>
            </div>
            <div class="wf-step-editor-field">
                <label>В отделе</label>
                <select onchange="updateStepProperty(${idx}, 'assignee_department_id', this.value ? parseInt(this.value) : null)">
                    <option value="">— Отдел автора —</option>
                    ${deptOptions}
                </select>
            </div>
        `;
    }
    
    // 5. Роль
    if (assigneeType === 'role') {
        const roleOptions = stepEditorRoles.map(r => {
            const selected = step.assignee_role_id === r.id ? 'selected' : '';
            return `<option value="${r.id}" ${selected}>${escapeHtml(r.name)}</option>`;
        }).join('');
        
        return `
            <div class="wf-step-editor-field">
                <label>Роль *</label>
                <select onchange="updateStepProperty(${idx}, 'assignee_role_id', this.value ? parseInt(this.value) : null)">
                    <option value="">— Выберите роль —</option>
                    ${roleOptions}
                </select>
            </div>
        `;
    }
    
    return '';
}
/**
 * Обновить свойство выбранного этапа
 */
function updateStepProperty(idx, prop, value) {
    const step = currentWorkflowSteps[idx];
    if (!step) return;
    
    step[prop] = value;
    
    // Обновляем карточку слева
    renderWorkflowSteps();
    
    // Если меняли то, что влияет на правую панель — обновляем и её
    if (prop === 'type' || prop === 'assignee_type' || 
        prop === 'assignee_post_id' || prop === 'assignee_department_id' || prop === 'assignee_role_id') {
        renderStepProperties();
    }
}


